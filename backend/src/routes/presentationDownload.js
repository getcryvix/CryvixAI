import express from "express";
import pptxgen from "pptxgenjs";

const router = express.Router();

router.post("/", async (req, res) => {
  try {
    const { topic, presentation } = req.body;

    if (!presentation) {
      return res.status(400).json({
        error: "Presentation content is required.",
      });
    }

    const pptx = new pptxgen();

    pptx.layout = "LAYOUT_WIDE";
    pptx.author = "CryvixAI";
    pptx.company = "CryvixAI";
    pptx.subject = topic || "AI Presentation";
    pptx.title = topic || "Presentation";
    pptx.lang = "en-US";

    // Title Slide
    let slide = pptx.addSlide();

    slide.background = { color: "0F172A" };

    slide.addText(topic || "AI Presentation", {
      x: 0.6,
      y: 0.8,
      w: 11,
      h: 0.8,
      fontSize: 28,
      bold: true,
      color: "FFFFFF",
    });

    slide.addText("Generated by CryvixAI", {
      x: 0.6,
      y: 1.7,
      w: 8,
      h: 0.4,
      fontSize: 16,
      color: "38BDF8",
    });

    // Content Slides
    const sections = presentation.split("##");

    sections.forEach((section) => {
      const text = section.trim();

      if (!text) return;

      const lines = text.split("\n");

      const title = lines[0] || "Slide";

      const body = lines.slice(1).join("\n");

      const s = pptx.addSlide();

      s.background = { color: "FFFFFF" };

      s.addText(title, {
        x: 0.5,
        y: 0.4,
        w: 11,
        h: 0.6,
        fontSize: 22,
        bold: true,
        color: "2563EB",
      });

      s.addText(body, {
        x: 0.6,
        y: 1.2,
        w: 11.5,
        h: 5.5,
        fontSize: 18,
        color: "222222",
        breakLine: false,
      });
    });

    const buffer = await pptx.write("nodebuffer");

    res.setHeader(
      "Content-Type",
      "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    );

    res.setHeader(
      "Content-Disposition",
      `attachment; filename="${(topic || "Presentation").replace(/\s+/g, "_")}.pptx"`
    );

    res.send(buffer);
  } catch (error) {
    console.error("PPT DOWNLOAD ERROR:", error);

    res.status(500).json({
      error: "Failed to generate PowerPoint.",
    });
  }
});

export default router;